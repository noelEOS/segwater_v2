"""DEPRECATED (2026-07-30) — superseded by ``ship/gen_ship_configs.py``.

Kept as the **executable record** of the 9 tracked Hampyeong gate inference
configs it produced (2026-07-25 checkpoint-selection gate). Do not generate NEW
configs with it.

What its local `resolve()` (below) lacks that `gen_ship_configs.py` has via
``ckptsel`` — this is the WEAKEST of the four gate copies:
  * **Silently swallows ambiguity.** `return c[0] if len(c) == 1 else None`
    collapses "no `*_last.pth`" and "THREE `*_last.pth`" into the same `None`,
    printing nothing about which happened or what the candidates were. The
    sibling `gen_demak_gate_configs.py` at least prints an `expected 1 match,
    got N` line. `ckptsel.resolve_last` raises `CkptSelError` listing the
    candidate filenames.
  * **Returns None instead of raising**, so `main()` continues and emits a
    partial set of configs (8 of 9) with only a trailing MISSING line.
  * **No `_last.pth` guard on the `best` arm.** `best.pth` is accepted on
    `exists()` alone; if it points at a `*_last.pth` the best and last arms
    become the same weights — undetected here, refused by
    `ckptsel.resolve_best`.
  * **No seed-token check** — a checkpoint copied into the wrong seed dir passes
    (`ckptsel.require_seed_token`), and **no sha256 distinctness check** across
    arms (`ckptsel.assert_distinct_weights`).
  * **No prefix-collision check** on the emitted `gate_{arm}_hampyeong_{seed}`
    sweep names (`naming.require_no_prefix_collisions`).

Original docstring: generate the 9 Hampyeong gate inference configs (3 seeds x
best/last/swa5); mirrors the tracked hampyeong sweep configs exactly (keep_top_k
5, length filter OFF, native224-s32); only sweep.name and the single checkpoint
differ per arm.
"""
from pathlib import Path
import sys

MODEL = "upernet_tu-swin_base_patch4_window7_224"
STAGE2 = Path("outputs/stage2") / MODEL
SEEDS = ["s19", "s42", "s58"]
OUT = Path("/home/noel/configs/hampyeong_gate")

TEMPLATE = """\
# Hampyeong gate — Swin-B stage2, seed {seed}, arm "{arm}".
# Generated by gen_hampyeong_configs.py. Settings mirror the tracked
# dev_sweep_all_hampyeong configs exactly (length filter OFF, keep_top_k 5).

sweep:
  name: "gate_{arm}_hampyeong_{seed}"
  dry_run: false
  continue_on_error: true

  input_dir: "/home/noel/hampyeong_ron_134_ts_16_sn_15"
  input_glob: "S1B_*.tif"

  common_overrides:
    inference.post_processing.smoothing.apply_simplification: true
    inference.post_processing.smoothing.simplify_tolerance_meters: 1.0
    inference.post_processing.filtering.apply_length_filter: false
    inference.post_processing.filtering.min_length_meters: 10000.0
    inference.post_processing.filtering.keep_top_k: 5
    inference.data.edge_policy: "shift_inward"
    inference.stitching.min_weight: 0.001

  checkpoints:
    - name: "upernet_swin_base_224_{arm}"
      checkpoint_path: "{ckpt}"
      model:
        arch: "upernet"
        encoder_name: "tu-swin_base_patch4_window7_224"

  presets:
    - name: "native224_weighted_224_b0_s32"
      overrides:
        inference.data.tile_size: 224
        inference.data.buffer_size: 0
        inference.data.stride: 32
        inference.stitching.mode: "weighted_blend"
        inference.stitching.blend_window: "hann"
"""


def resolve(seed_dir: Path, arm: str):
    if arm == "best":
        p = seed_dir / "best.pth"
        return p if p.exists() else None
    pat = "*_last.pth" if arm == "last" else "*_swa5_step*.pth"
    c = sorted(seed_dir.glob(pat))
    return c[0] if len(c) == 1 else None


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    written, missing = [], []
    for seed in SEEDS:
        for arm in ["best", "last", "swa5"]:
            ckpt = resolve(STAGE2 / seed, arm)
            if ckpt is None:
                missing.append("%s/%s" % (seed, arm))
                continue
            real = ckpt.resolve().relative_to(Path.cwd()) if ckpt.is_symlink() else ckpt
            cfg = OUT / ("gate_%s_hampyeong_%s.yaml" % (arm, seed))
            cfg.write_text(TEMPLATE.format(seed=seed, arm=arm, ckpt=str(real)))
            written.append((cfg.name, str(real).split("/")[-1]))
    print("=== WROTE %d configs ===" % len(written))
    for n, c in written:
        print("  %-34s -> %s" % (n, c))
    if missing:
        print("=== MISSING: %s ===" % ", ".join(missing))
        sys.exit(1)


if __name__ == "__main__":
    main()
