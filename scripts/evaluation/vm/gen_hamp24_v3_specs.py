"""Emit the three v3 hamp24 scoring specs (one per valid-mask extent).

Same instrument as the pair-based hamp24 campaign -- same 24 dates, same GT
flood masks, same three extents -- with two differences that must be explicit:

* 6 arms (2 archs x 3 seeds), not 21. The v3 lineage trained Swin-B and
  ConvNeXtV2-Base only.
* ``lineage_slug: v3`` / ``training_data: dataset_v3`` tag every output row, so
  a v3 number can never be pooled with a pair-based one by accident. A
  Hampyeong IoU is only identifiable with its date set, extent AND aggregation
  (IOU_ESTIMANDS_hampyeong.md); lineage is now a fourth axis.

run_dir globs anchor on the ``_<UTC stamp>_`` the sweep always emits, so a name
that is a prefix of another cannot match two dirs.
"""
import pathlib, yaml

EXTENTS = {
    "nominal": (
        "/home/noel/ancillary/hampyeong/nas_root/Tide_Gauge/Korean_Peninsula"
        "/DEM_wrt_WGS84_TBM/DEM_VALID_MASK_aoi.tif", 1179967),
    "full_bay": (
        "/home/noel/ancillary/hampyeong/valid_masks_extents"
        "/DEM_VALID_MASK_aoi_extended_full_bay.tif", 1273639),
    "bridge_south": (
        "/home/noel/ancillary/hampyeong/valid_masks_extents"
        "/DEM_VALID_MASK_aoi_extended_bridge_south.tif", 850837),
}
ARCHS = [
    ("Swin-B", "swin_b", "swinb", "upernet_tu-swin_base_patch4_window7_224"),
    ("ConvNeXtV2", "convnextv2", "cnxb", "upernet_tu-convnextv2_base"),
]

CFG = pathlib.Path("scripts/evaluation/vm/configs/hampyeong")


def checkpoint_for(tok, seed):
    """Read the checkpoint out of the inference config that produced the run.

    Taking it from the config rather than restating it keeps the spec's
    provenance audit meaningful: if the two disagreed, the audit would be
    comparing the spec against itself.
    """
    doc = yaml.safe_load((CFG / f"inference_sweep_v3_hamp24_{tok}_s{seed}.yaml").read_text())
    return doc["sweep"]["checkpoints"][0]["checkpoint_path"]
SEEDS = [19, 42, 58]
OUT = pathlib.Path("scripts/evaluation/vm/specs")

for ext, (mask, npx) in EXTENTS.items():
    lines = [
        f"# hamp24 scoring spec, dataset_v3 lineage -- {ext} extent.",
        "# Generated by gen_hamp24_v3_specs.py. 6 arms (2 archs x 3 seeds), 24 dates.",
        "# Checkpoints are the deployed *_last.pth arm of each stage-2 v3 run.",
        "repo: /home/noel/segwater_v2",
        # Run dirs live under outputs/inference/runs/. The pair-based specs say
        # outputs/inference because that campaign ran on a flatter layout.
        "pair_root: outputs/inference/runs",
        "dates_csv: /home/noel/hampyeong_ron_134_ts_16_sn_15_all24/pairing_metadata.csv",
        f"gt_dir: /home/noel/ancillary/hampyeong/gt_flood_masks_24_floorminute/{ext}",
        f"valid_mask: {mask}",
        f"expected_valid_pixels: {npx}",
        "variant_column: false",
        "lineage_slug: v3",
        "training_data: dataset_v3",
        f"output: /home/noel/hamp24_v3_per_date_metrics_{ext}.csv",
        "",
        "entries:",
    ]
    for label, slug, tok, arch in ARCHS:
        for s in SEEDS:
            lines.append(
                f'  - {{label: "{label}", slug: {slug}, seed: {s}, '
                f'run_dir: "glob:v3_hamp24_{tok}_s{s}_*_{arch}_s{s}_native224_weighted_224_b0_s32", '
                f'checkpoint: {checkpoint_for(tok, s)}}}')
    p = OUT / f"hamp24_v3_{ext}.yaml"
    p.write_text("\n".join(lines) + "\n")
    print("wrote", p)
